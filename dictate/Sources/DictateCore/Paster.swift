import AppKit
import ApplicationServices
import Carbon
import Foundation

/// Puts text at the cursor of the app you were in: clipboard + ⌘V, then your clipboard is restored.
public enum Paster {
    public enum Outcome: Equatable, Sendable {
        case verified          // the text box now contains the text (read back through Accessibility)
        case sent              // ⌘V was sent to the right app, but this app doesn't let us read its text box
        case wrongApp          // the target app didn't come to the front; nothing was sent
        case noPermission      // Accessibility is off: macOS silently drops the ⌘V
        case secure            // a password field
    }

    /// macOS turns this on in password fields; we never paste dictation into those.
    public static var isSecureInputActive: Bool { IsSecureEventInputEnabled() }

    /// Clipboard managers skip items marked like this (nspasteboard.org convention), so dictation doesn't flood them.
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    @MainActor
    public static func paste(_ text: String, into app: NSRunningApplication?) async -> Outcome {
        if isSecureInputActive { return .secure }
        guard AXIsProcessTrusted() else { return .noPermission }

        // 1. The target app must really be in front before ⌘V, or the keystroke goes elsewhere.
        if let app, NSWorkspace.shared.frontmostApplication?.processIdentifier != app.processIdentifier {
            app.activate()
            var waited = 0
            while NSWorkspace.shared.frontmostApplication?.processIdentifier != app.processIdentifier, waited < 800 {
                try? await Task.sleep(nanoseconds: 20_000_000); waited += 20
            }
            guard NSWorkspace.shared.frontmostApplication?.processIdentifier == app.processIdentifier else { return .wrongApp }
            try? await Task.sleep(nanoseconds: 80_000_000)      // let it restore keyboard focus to its text box
        }
        let before = FocusProbe.focusedValue(in: app)

        // 2. Clipboard: save everything (all types) so it can be put back exactly.
        let pb = NSPasteboard.general
        let saved: [[NSPasteboard.PasteboardType: Data]] = (pb.pasteboardItems ?? []).map { item in
            var d: [NSPasteboard.PasteboardType: Data] = [:]
            for t in item.types { if let v = item.data(forType: t) { d[t] = v } }
            return d
        }
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transient)
        item.setData(Data(), forType: autoGenerated)
        pb.writeObjects([item])
        let ours = pb.changeCount

        // 3. ⌘V
        let src = CGEventSource(stateID: .hidSystemState)
        let v = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)

        // 4. Check the text arrived, where the app lets us read its text box (native apps; most web/Electron don't).
        var outcome = Outcome.sent
        if before != nil {
            for _ in 0..<15 {
                try? await Task.sleep(nanoseconds: 40_000_000)
                if let now = FocusProbe.focusedValue(in: app), now != before, now.contains(text.prefix(40)) { outcome = .verified; break }
            }
        }

        // 5. Put your clipboard back — later, because web and Electron apps read it asynchronously, and only if
        //    nobody copied something new in the meantime.
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 1_500_000_000)
            guard pb.changeCount == ours else { return }
            pb.clearContents()
            if !saved.isEmpty {
                pb.writeObjects(saved.map { d -> NSPasteboardItem in
                    let item = NSPasteboardItem()
                    for (t, v) in d { item.setData(v, forType: t) }
                    return item
                })
            }
        }
        return outcome
    }
}
